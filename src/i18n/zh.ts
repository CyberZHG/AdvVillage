function num(n: number): string {
  n = Math.floor(n);
  if (Math.abs(n) >= 1e8) return (n / 1e8).toFixed(2) + '亿';
  if (Math.abs(n) >= 1e5) return (n / 1e4).toFixed(1) + '万';
  return n.toLocaleString('en-US');
}

